import assert from 'node:assert/strict';
import { walkLink } from '../src/walkmode/walkLink';
import { roomTourUrl } from '../src/components/walkEntry';
import { walkShareMeta } from '../src/walkmode/shareMeta';
import { expandWalkQuery, compactWalkUrl } from '../src/walkmode/walkQuery';

const name = '강남데시앙포레', id = '11680:수서동:795:강남데시앙포레';
const url = new URL(walkLink(37.5, 127.05, 7, { name, complexId: id }), 'https://kospimap.com');
const expanded = expandWalkQuery(url.searchParams);
assert.equal(expanded.get('id'), id);
assert.equal(expanded.get('f'), '7');
assert.ok(!url.searchParams.has('name') && !url.searchParams.has('id'));
assert.equal(walkShareMeta(url.searchParams).title, '강남데시앙포레 | 룸투어(임장) | KOSPIMAP');
assert.equal(walkShareMeta(new URLSearchParams({ id })).title, walkShareMeta(url.searchParams).title);
assert.equal(walkShareMeta(new URL(roomTourUrl('11680:123', 84, '/realestate-map', name), url).searchParams).title, walkShareMeta(url.searchParams).title);
const tour = new URL(roomTourUrl(id, 84.86, '/realestate-map?sgg=11680&name=long-return-state', name), url);
assert.ok(tour.href.length < 100, tour.href);
assert.deepEqual([...tour.searchParams.keys()], ['c', 'a']);
assert.equal(expandWalkQuery(tour.searchParams).get('tour'), '1');
assert.equal(expandWalkQuery(tour.searchParams).get('area'), '84.86');
assert.equal(compactWalkUrl(expandWalkQuery(tour.searchParams)), tour.pathname + tour.search);
assert.equal(expandWalkQuery(new URLSearchParams('c=bad_')).get('id'), null);
assert.equal(walkShareMeta(new URLSearchParams()).title, '룸투어(임장) | KOSPIMAP');
assert.equal(walkLink(37.5, 127.05, -2), '/walk?at=37.500000,127.050000&f=-2');
console.log('PASS apartment names and destinations survive room-tour sharing');
