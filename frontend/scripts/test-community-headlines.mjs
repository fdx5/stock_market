import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const dir=await mkdtemp(path.join(tmpdir(),'community-headlines-')),file=path.join(dir,'model.mjs');
await build({entryPoints:['src/neo/headlineFeedModel.ts'],outfile:file,bundle:true,format:'esm',platform:'node'});
const {latestHeadlines,communityPostUrl}=await import(pathToFileURL(file));
const rows=Array.from({length:25},(_,i)=>({id:`pp-stock-${i}`,title:`Article ${i}`,source:i<15?'Ppomppu':i<20?'Damoang':'Clien',url:`https://example.org/${i}`,published_at:new Date(Date.UTC(2026,10,7,12,59-i)).toISOString()}));
const selected=latestHeadlines([...rows,rows[0],{...rows[0],id:'bad',url:'javascript:evil()'}]);
assert.equal(selected.length,10);
assert.equal(new Set(selected.map(p=>p.id)).size,10);
assert.equal(new Set(selected.map(p=>p.source)).size,3,'one busy source must not monopolize the reel');
assert.ok(selected.every((p,i)=>!i||p.published_at<=selected[i-1].published_at));
assert.equal(latestHeadlines(rows.slice(0,15)).length,10,'quiet sources must not leave empty slots');
const internal=new URL(communityPostUrl('kr','pp-stock-42','a'.repeat(32)),'https://kospimap.com');
assert.equal(internal.origin,'https://kospimap.com');
assert.equal(internal.pathname,'/community/kr');
assert.equal(internal.searchParams.get('post_id'),'pp-stock-42');
assert.equal(internal.searchParams.get('snapshot'),'a'.repeat(32));
assert.ok(!communityPostUrl('property','82-42','bad').includes('snapshot'));
const now=Date.UTC(2026,10,7,13);
const fresh=rows.slice(0,12).map((p,i)=>({...p,source:'Busy source',published_at:new Date(now-(i+1)*60_000).toISOString()}));
const old=rows.slice(12).map((p,i)=>({...p,source:'Quiet '+i,published_at:new Date(now-7_200_000-i*60_000).toISOString()}));
assert.ok(latestHeadlines([...fresh,...old],now).every(p=>Date.parse(p.published_at)>now-3_600_000),'old sources must not displace available fresh posts');
console.log('Community headline mix, ordering, internal article URLs and snapshot validation passed');
