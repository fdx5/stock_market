import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const dir=await mkdtemp(path.join(tmpdir(),'traffic-cctv-')),out=path.join(dir,'cctv.mjs');
await build({entryPoints:['src/components/trafficCctv.ts'],outfile:out,bundle:true,format:'esm',platform:'node'});
const {cameraFromFeature,cameraPoint,mergeCameras,loadCameras}=await import(pathToFileURL(out));
const feature={id:'test1',geometry:{type:'Point',coordinates:[127,37.5]},properties:{cctvname:'Test Bridge',locate:'Seoul'}};
const c=cameraFromFeature(feature);assert.equal(c.name,'Test Bridge');assert.equal(c.address,'Seoul');
assert.equal(cameraFromFeature({...feature,geometry:{type:'Point',coordinates:[37.5,127]}}),null);
assert.equal(cameraFromFeature({...feature,properties:{}}),null);
assert.equal(cameraFromFeature({...feature,geometry:{type:'Polygon',coordinates:[]}}),null);
assert.deepEqual(cameraPoint(c,c),{x:0,y:0});
const video={...c,id:'its:bridge',media:'/api/realestate/cctv/media/fixture'};
assert.equal(mergeCameras([c,video],c).length,1);assert.equal(mergeCameras([c,video],c)[0].id,video.id);
const next={...c,id:'other',lon:127.002};assert.equal(mergeCameras([c,next],c).length,2,'same camera name at different positions stays separate');
const opposite={...c,id:'opposite',name:'Other direction',lon:127.00001};assert.equal(mergeCameras([video,opposite],c).length,2,'opposite camera names stay separate');
assert.equal(mergeCameras(Array.from({length:800},(_,i)=>({...c,id:`c${i}`,name:`camera ${i}`})),c).length,500);
const crowded=Array.from({length:600},(_,i)=>({...c,id:`near${i}`,name:`near ${i}`}));
const distantVideo={...video,id:'its:distant',name:'Actual traffic video',lon:127.015};
const prioritized=mergeCameras([...crowded,distantVideo],c);
assert.equal(prioritized[0].id,distantVideo.id,'location-only registry density must not hide a real video camera');
const previousFetch=globalThis.fetch,previousWindow=globalThis.window,previousDocument=globalThis.document,calls=[];
try{
  globalThis.window={};globalThis.document={createElement:()=>assert.fail('unapproved city CCTV must not be requested')};
  globalThis.fetch=async url=>{calls.push(url);return {ok:true,json:async()=>({items:[c,video,{...video,id:'utic:pending'}],status:'ok'})};};
  const loaded=await loadCameras(37.5,127,'fixture','fixture',new AbortController().signal,true);
  assert.ok(calls[0].includes('fresh=true'),'reconnecting video must renew the server link too');
  assert.deepEqual(loaded.items.map(c=>c.id),[video.id],'only playable ITS cameras are linked while city approval is pending');
  assert.equal(loaded.locationFailed,false,'disabled city lookup is not a failed provider');
  globalThis.fetch=async()=>({ok:true,json:async()=>({items:[],status:'unavailable',issues:[{road:'ex',code:'connect_timeout'}]})});
  const failed=await loadCameras(37.5,127,'fixture','fixture',new AbortController().signal,true);
  assert.equal(failed.locationFailed,true,'an unavailable feed must not be presented as no nearby cameras');
  assert.equal(failed.connectionFailed,true);
  globalThis.fetch=async()=>({ok:true,json:async()=>({items:[],status:'ok'})});
  assert.equal((await loadCameras(37.5,127,'fixture','fixture',new AbortController().signal,true)).locationFailed,false,'a valid empty area stays distinct from provider failure');
}finally{globalThis.fetch=previousFetch;globalThis.window=previousWindow;globalThis.document=previousDocument;}
const radarOut=path.join(dir,'radar.mjs');
await build({entryPoints:['src/components/droneRadarCctv.ts'],outfile:radarOut,bundle:true,format:'esm',platform:'node'});
const {cameraRadarZoom,radarCameraPoint}=await import(pathToFileURL(radarOut));
for(const size of [92,116,132,210,420])for(const lat of [33.5,37.4289,38.5]){
  const distances=[1370,2300,3250],z=cameraRadarZoom(lat,size,distances),mpp=40075016.7*Math.cos(lat*Math.PI/180)/(256*2**z);
  for(const distance of distances)assert.ok(distance/mpp<=size/2-22,'camera icons must fit inside the round map at desktop and mobile sizes');
}
assert.deepEqual(radarCameraPoint(100,0,0,0,10,210,0),{x:115,y:105,visible:true});
const rotated=radarCameraPoint(100,0,0,0,10,210,-Math.PI/2);
assert.ok(Math.abs(rotated.x-105)<1e-6&&Math.abs(rotated.y-95)<1e-6,'heading-up map keeps camera hit targets on their icons');
assert.equal(radarCameraPoint(3000,0,0,0,10,210,0).visible,false,'off-map cameras must not become false on-map locations');
console.log('CCTV: provider failures, city isolation, coordinates, merge limits, radar fit and rotated hit targets passed');
